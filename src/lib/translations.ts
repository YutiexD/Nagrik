// Fallback to English, then to empty string
export function getTranslation(lang: string, key: string): string {
  const targetLang = translations[lang] || translations["en"];
  return targetLang[key] || translations["en"][key] || key;
}

export function getLocalizedText(
  value: string | { en: string; local: string } | undefined | null,
  lang: string | null,
  t: (key: string) => string
): string {
  if (!value) return "";
  if (typeof value === "string") {
    const translated = t(value);
    if (translated && translated !== value) return translated;
    return value;
  }
  
  // If it's a dual-language object
  if (!lang || lang === "en") {
    return value.en || "";
  }
  
  // Try translating the English text from dictionary first
  const translatedEn = t(value.en);
  if (translatedEn && translatedEn !== value.en) {
    return translatedEn;
  }
  
  // Fallback to local translation or English value
  return value.local || value.en || "";
}
